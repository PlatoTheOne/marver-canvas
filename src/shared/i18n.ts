/** 将外部语言值收敛为 Marver 支持的 locale。 */
export function resolveLocale(value: unknown): Locale {
  if (typeof value !== 'string') return DEFAULT_LOCALE
  const normalized = value.trim().replace('_', '-').toLowerCase()
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  if (normalized === 'zh-hk') return 'zh-HK'
  if (normalized === 'zh-tw' || normalized === 'zh-hant') return 'zh-TW'
  if (normalized === 'zh' || normalized === 'zh-cn' || normalized === 'zh-sg' || normalized === 'zh-hans') return 'zh-CN'
  return DEFAULT_LOCALE
}

/** 返回适合写入 HTML lang 属性的标准语言标签。 */
export function htmlLang(locale: unknown): Locale {
  return resolveLocale(locale)
}

/** 用命名变量替换翻译中的 {{name}} 占位符。 */
function interpolate(message: string, vars?: Vars): string {
  if (!vars) return message
  return message.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(vars[key] ?? `{{${key}}}`))
}

/** 按 locale 读取文案；缺失时返回英文原文，避免界面出现内部 key。 */
export function translate(locale: unknown, english: string, vars?: Vars): string {
  const resolved = resolveLocale(locale)
  const table = resolved === 'zh-CN' ? zhCN : resolved === 'en' ? undefined : zhHant
  return interpolate(table?.[english] ?? english, vars)
}

let activeLocale: Locale = DEFAULT_LOCALE

/** 设置浏览器壳层当前语言。 */
export function setLocale(locale: unknown): Locale {
  activeLocale = resolveLocale(locale)
  return activeLocale
}

/** 翻译浏览器壳层文案。 */
export function t(english: string, vars?: Vars): string {
  return translate(activeLocale, english, vars)
}

/** 创建绑定 locale 的服务端翻译函数。 */
export function translator(locale: unknown): (english: string, vars?: Vars) => string {
  const resolved = resolveLocale(locale)
  return (english, vars) => translate(resolved, english, vars)
}
